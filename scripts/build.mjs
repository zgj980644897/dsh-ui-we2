// Zero-dependency bundler: inlines src/theme.css into the browser module-table
// bundle. The shipped client.js is generated; edit the sources and rerun
// `node scripts/build.mjs`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const css = readFileSync(join(root, 'src/theme.css'), 'utf8')
const body = readFileSync(join(root, 'src/client.js'), 'utf8').replace('__WE2_CSS__', JSON.stringify(css))

const bundle = `// Generated by scripts/build.mjs from src/client.js + src/theme.css. Do not edit.
window.__ModuleLoader__.load({
  id: 'dsh-ui-we2',
  factory: (require) => {
${body}
  },
})
`

mkdirSync(join(root, 'lib'), { recursive: true })
writeFileSync(join(root, 'lib/client.js'), bundle)
console.log(`lib/client.js  ${(bundle.length / 1024).toFixed(1)} KiB`)
